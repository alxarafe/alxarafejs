#!/usr/bin/env node
// Genera apps/web/src/app/module-routes.generated.ts (gitignored) a partir del
// artefacto `web` de .cache/manifest.json. Sin caché o sin módulos web, el
// archivo queda vacío para no romper el build de un clon limpio.
//
// Variables de entorno:
//   ROOT          raíz del workspace (default: repo)
//   CACHE_DIR     carpeta de caché (default: <ROOT>/.cache)
//   OUT_FILE      archivo generado (default: <ROOT>/apps/web/src/app/module-routes.generated.ts)

import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(process.env.ROOT ?? join(HERE, ".."));
const CACHE = resolve(process.env.CACHE_DIR ?? join(ROOT, ".cache"));
const OUT = resolve(process.env.OUT_FILE ?? join(ROOT, "apps", "web", "src", "app", "module-routes.generated.ts"));

const MANIFEST = join(CACHE, "manifest.json");

function pageClass(file) {
	const re = /export\s+class\s+([A-Z][A-Za-z0-9]*Page)\b/;
	let src = "";
	try {
		src = readFileSync(file, "utf8");
	} catch {
		return null;
	}
	return re.exec(src)?.[1] ?? null;
}

function relToCacheEntry(moduleName, entry) {
	const fromDir = join(ROOT, "apps", "web", "src", "app");
	return relative(fromDir, join(CACHE, "web", moduleName, entry)).replaceAll("\\", "/");
}

let modules = [];
if (existsSync(MANIFEST)) {
	const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
	const hasWeb = (manifest.artifacts ?? []).some((a) => a.name === "web");
	modules = hasWeb ? (manifest.activeModules ?? []).filter((m) => m.manifest?.web) : [];
}

const routes = [];
for (const m of modules) {
	const web = m.manifest.web;
	const entry = web.entry.replace(/\.ts$/, "");
	const file = join(CACHE, "web", m.name, entry);
	const klass =
		pageClass(file) ?? `${entry.split("/").pop().charAt(0).toUpperCase() + entry.split("/").pop().slice(1)}Page`;
	const path = web.mountPath.replace(/^\/+/, "");
	routes.push(
		`  {\n    path: ${JSON.stringify(path)},\n    canActivate: [authGuard],\n    loadComponent: () => import(${JSON.stringify(relToCacheEntry(m.name, entry))}).then((m) => m.${klass}),\n  },`,
	);
}

const body = [
	"/* GENERATED by scripts/generate-module-routes.mjs — do not edit. */",
	"import { Routes } from '@angular/router';",
	"import { authGuard } from './core/guards/auth.guard';",
	"",
	"export const moduleRoutes: Routes = [",
	...routes,
	"];",
	"",
].join("\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);

// Los web/ de los módulos viven fuera de apps/web: sin un node_modules propio
// no resolverían @angular/* ni rxjs (pnpm los instala solo en apps/web). Se
// enlaza el node_modules de la app dentro de la caché para que tsc y esbuild
// resuelvan igual que desde src/app.
const webDir = join(CACHE, "web");
const link = join(webDir, "node_modules");
if (modules.length > 0) {
	mkdirSync(webDir, { recursive: true });
	rmSync(link, { recursive: true, force: true });
	try {
		symlinkSync(relative(webDir, join(ROOT, "apps", "web", "node_modules")), link, "dir");
	} catch (err) {
		console.error(`module-routes: no se pudo enlazar node_modules en la caché: ${err.message}`);
	}
} else if (existsSync(link)) {
	rmSync(link, { recursive: true, force: true });
}

console.log(`module-routes: ${routes.length} ruta(s) de módulo -> ${OUT}`);
